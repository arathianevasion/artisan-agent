# An open decision a worker finds in another ticket (#231): it is filed for
# triage through questions.sh, non-blocking and raised by a finding, instead
# of being commented on or relayed; the target is not blocked by the filing,
# and only a ruling that asks for the block makes `questions.sh sync` add it.
# Fake `gh` (a folder tracker) stands in for the real one.

. "$TESTS_DIR/helpers/run-state.sh"

Q="$PLUGIN_ROOT/scripts/questions.sh"
F="$PLUGIN_ROOT/scripts/findings.sh"
TRIAGE="$PLUGIN_ROOT/skills/triage/SKILL.md"

# Tickets 1 and 2 in a run r1 on a fake tracker that also holds ticket 3,
# outside the run.
run_with_tracker() {
  make_project
  export FAKE_GH_DIR="$TEST_TMPDIR/tracker"
  mkdir -p "$FAKE_GH_DIR"
  local n=""
  for n in 1 2 3; do
    jq -n --argjson n "$n" '{number: $n, title: "Ticket \($n)", state: "open", labels: [], body: "- [ ] it works"}' >"$FAKE_GH_DIR/issue-$n.json"
  done
  PATH="$TESTS_DIR/fixtures/fake-gh:$PATH"
  export PATH
  unset ARTISAN_RUN_ID ARTISAN_FINDINGS_FILE
  jq -n '{
    run_id: "r1", repo: "local/sample", integration_branch: "run/r1", scope: ["1", "2"],
    waves: [["1", "2"]], max_agents: 2, attempts_per_ticket: 2, suite_command: "true",
    orchestrator: {estimate_usd: 0.25},
    tickets: {
      "1": {title: "Ticket 1", expected_files: ["one.txt"], model: "claude-sonnet-5-5", estimate_usd: 0.25, expected: {minutes: 5}, caps: {max_budget_usd: 0.5, max_turns: 20, deadline_seconds: 120}},
      "2": {title: "Ticket 2", expected_files: ["two.txt"], model: "claude-sonnet-5-5", estimate_usd: 0.25, expected: {minutes: 5}, caps: {max_budget_usd: 0.5, max_turns: 20, deadline_seconds: 120}}}}' >"$TEST_TMPDIR/plan.json"
  "$SCRIPTS/state.sh" init "$RUN_DIR" "$TEST_TMPDIR/plan.json"
  ARTISAN_WRITER_PID=$(start_worker)
  export ARTISAN_WRITER_PID
  trap kill_workers EXIT
}

# found <target>: ticket 1's worker files an open decision it found in
# <target>, as the implement skill says; the sweep reads its findings line.
# Prints the open decision's number.
found() {
  local q=""
  q=$(ARTISAN_FINDINGS_FILE="$RUN_DIR/results/findings/1.jsonl" ARTISAN_RUN_ID=r1 \
    "$Q" file --ticket "$1" --criterion 8 --case incomplete \
      --harm "Ticket $1's Export button offers PDF, and nothing can render a PDF yet" \
      --recommendation "Hide the PDF option until the renderer lands" \
      --non-blocking --raised-by finding --from 1 --repo local/sample)
  "$SCRIPTS/sweep.sh" "$RUN_DIR" >/dev/null 2>&1
  printf '%s\n' "$q"
}

comment() { printf '%s\n---\n' "$2" >>"$FAKE_GH_DIR/comments-$1.md"; }

test_a_finding_open_decision_is_filed_non_blocking_and_never_commented_on_or_relayed() {
  run_with_tracker
  local st="" q=""
  q=$(found 2)
  assert_contains "$(jq -r .body "$FAKE_GH_DIR/issue-$q.json")" "Raised at: finding, by the worker of #1, in another ticket"
  assert_contains "$(jq -r .body "$FAKE_GH_DIR/issue-$q.json")" "Filed without blocking #2"
  assert_eq needs-triage "$(jq -r '[.labels[].name] | join(",")' "$FAKE_GH_DIR/issue-$q.json")"
  # Neither relayed (#2 in flight) nor commented (#2 queued or with the Artisan).
  for st in in_flight queued blocked; do
    "$SCRIPTS/state.sh" update "$RUN_DIR" ".tickets[\"2\"].status = \"$st\""
    assert_eq "" "$("$F" pending "$RUN_DIR")" "pending with #2 $st"
  done
  assert_not_contains "$(cat "$FAKE_GH_DIR/calls")" "issue comment"
  # The Decision chat's ruling on it reaches the run: it sits on #2.
  assert_eq "$q false open finding 1" \
    "$(state_get '.tickets["2"].questions[0] | "\(.ticket) \(.blocking) \(.state) \(.raised_by) \(.from)"')"
  # The sweep registers it once.
  "$SCRIPTS/state.sh" update "$RUN_DIR" '.tickets["2"].status = "queued"'
  "$SCRIPTS/sweep.sh" "$RUN_DIR" >/dev/null 2>&1
  assert_eq 1 "$(state_get '.tickets["2"].questions | length')"
}

test_the_target_ticket_is_not_blocked_by_the_filing() {
  run_with_tracker
  local q=""
  q=$(found 2)
  assert_not_contains "$(cat "$FAKE_GH_DIR/calls")" "dependencies/blocked_by"
  [ ! -s "$FAKE_GH_DIR/blocked_by-2.json" ] || assert_eq "[]" "$(jq -c . "$FAKE_GH_DIR/blocked_by-2.json")"
  assert_eq queued "$(state_get '.tickets["2"].status')"
  assert_eq "open #2 #$q" "$("$Q" sync "$RUN_DIR")"
  assert_eq queued "$(state_get '.tickets["2"].status')"
  # Its own worker's ticket is not touched either.
  assert_eq null "$(state_get '.tickets["1"].questions')"
}

test_an_open_decision_in_a_ticket_outside_the_run_adds_no_ticket_to_it() {
  run_with_tracker
  local q=""
  q=$(found 3)
  assert_eq null "$(state_get '.tickets["3"]')"
  assert_eq "" "$("$F" pending "$RUN_DIR")"
  assert_not_contains "$(cat "$FAKE_GH_DIR/calls")" "issue comment"
}

test_a_ruling_that_asks_for_the_block_makes_sync_add_it_on_the_tracker() {
  run_with_tracker
  local q="" calls=""
  q=$(found 2)
  comment "$q" $'> *This was generated by AI during triage.*\n\nAdd the block: #2 must not go on until the formats are settled.'
  assert_eq "blocked #2 #$q" "$("$Q" sync "$RUN_DIR")"
  assert_eq "[$q]" "$(jq -c . "$FAKE_GH_DIR/blocked_by-2.json")"
  assert_eq blocked "$(state_get '.tickets["2"].status')"
  assert_eq "waiting on the answer to #$q" "$(state_get '.tickets["2"].blocked_reason')"
  assert_eq "true open" "$(state_get '.tickets["2"].questions[0] | "\(.blocking) \(.state)"')"
  assert_eq 1 "$(jq --arg q "$q" '[.events[] | select(.event == "block-added" and .ticket == "2" and .question == $q)] | length' "$RUN_DIR/state.json")"
  # Once only: the next sync sees an open question and adds nothing.
  calls=$(grep -c 'dependencies/blocked_by' "$FAKE_GH_DIR/calls")
  assert_eq "open #2 #$q" "$("$Q" sync "$RUN_DIR")"
  assert_eq "$calls" "$(grep -c 'dependencies/blocked_by' "$FAKE_GH_DIR/calls")"
  # The answer then lifts it as for any blocking question.
  comment "$q" $'Answer: offer PDF only once the renderer lands.\nTook the recommendation: yes\nNeeded the Decision chat: yes'
  jq '.state = "closed"' "$FAKE_GH_DIR/issue-$q.json" >"$TEST_TMPDIR/i" && mv "$TEST_TMPDIR/i" "$FAKE_GH_DIR/issue-$q.json"
  assert_eq "answered #2 #$q" "$("$Q" sync "$RUN_DIR")"
  assert_eq queued "$(state_get '.tickets["2"].status')"
}

test_a_block_ruling_on_a_ticket_in_flight_adds_the_edge_and_leaves_its_attempt_running() {
  run_with_tracker
  local q=""
  q=$(found 2)
  "$SCRIPTS/state.sh" update "$RUN_DIR" '.tickets["2"].status = "in_flight"'
  comment "$q" "Add the block: wait for the formats."
  assert_eq "blocked #2 #$q" "$("$Q" sync "$RUN_DIR")"
  assert_eq "[$q]" "$(jq -c . "$FAKE_GH_DIR/blocked_by-2.json")"
  assert_eq in_flight "$(state_get '.tickets["2"].status')"
  assert_eq true "$(state_get '.tickets["2"].questions[0].blocking')"
}

test_the_triage_skill_names_the_add_the_block_ruling_for_an_open_decision_in_another_ticket() {
  local section=""
  section=$(awk '/^## Worker questions/{on=1} on && /^## / && !/Worker questions/{exit} on' "$TRIAGE")
  assert_contains "$section" "Add the block:"
  assert_contains "$section" "Raised at: finding"
}

test_an_open_finding_decision_never_keeps_its_ticket_from_requeueing_on_its_own_answer() {
  run_with_tracker
  local own="" q=""
  q=$(found 2)
  own=$(ARTISAN_FINDINGS_FILE="$RUN_DIR/results/findings/2.jsonl" "$Q" file --ticket 2 --criterion 1 \
    --question "Which store?" --option A --option B --recommendation A --blocking --repo local/sample)
  "$SCRIPTS/state.sh" update "$RUN_DIR" '.tickets["2"].status = "blocked" | .tickets["2"].attempts = 1'
  "$SCRIPTS/sweep.sh" "$RUN_DIR" >/dev/null 2>&1
  "$Q" block "$RUN_DIR" 2
  comment "$own" "Answer: A"
  jq '.state = "closed"' "$FAKE_GH_DIR/issue-$own.json" >"$TEST_TMPDIR/i" && mv "$TEST_TMPDIR/i" "$FAKE_GH_DIR/issue-$own.json"
  assert_contains "$("$Q" sync "$RUN_DIR")" "answered #2 #$own"
  assert_eq queued "$(state_get '.tickets["2"].status')"
  assert_eq open "$(state_get '.tickets["2"].questions[0].state')"
}

test_a_block_ruling_on_a_merged_ticket_adds_nothing() {
